// BCPack BC6H (format 6) block rebuild, with a labelled fallback for blocks that depend on the
// format's 255-entry dictionary.
//
// LOCAL. Status (see out/gamerun/texdec_work/NOTES_BC6H.md):
// - Lane layout and the two references per block are shared with BC7 (bcpack_decoder.h).
// - Rebuild rules (written here independently from public prose descriptions of the format; no code
//   or table copied): the endpoint state holds the block's stored fields w, x, y, z per channel,
//   16-bit and top-aligned; a field of b bits is the state's top b bits plus a zigzag residual, mod
//   2^b; w residuals are lanes 2-4 (E, O bit-interleaved), x lanes 5-7, y = E and z = O of lanes 8-10.
//   Reference 0 starts from half range (0x8000 per field, index 8). 12- and 16-bit bases keep bits 10..
//   reversed in the state. One-region blocks set z = x and derive y from w. Indices as BC7 (lanes
//   11-14, 4-bit top-aligned state, 3-bit reads in two-region modes).
// - Measured locally: blocks whose index chain is free of the dictionary satisfy the BC6H anchor rule
//   every time (chance 7-16%); endpoint-clean blocks decode to plausible HDR values. Pixel exactness
//   against a reference decode is NOT established.
// - Missing: the dictionary. 93.5% of local BC6H blocks have an endpoint chain rooted in it, 70% an
//   index chain; only 0.8% are free of it in both. No dictionary is compiled in.
//
// Fallback (only when the caller asks for it): a block with both chains known is rebuilt exactly; one
// with known endpoints but unknown indices keeps its endpoints with flat mid indices; one with
// unknown endpoints copies the endpoints of the nearest block in stream order whose endpoints are
// known (flat indices); a stream with none gets a constant block. Counts are returned.
