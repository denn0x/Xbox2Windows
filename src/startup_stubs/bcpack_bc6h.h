// Second anchor of the 32 two-region partitions (the first 32 of BC7's ANCHOR_2).
inline uint8_t anchor2(uint8_t part) { return ANCHOR_2[part & 31]; }

struct Fields {
    uint8_t mode = 0, part = 0;
    uint16_t ep[4][3] = {};  // field values as the BC6H spec numbers their bits (LAYOUT places them)
    uint8_t idx[16] = {};
};

inline uint8_t field_bits(const Mode& m, int e, int c) {
    return (e == 0 || !m.transformed) ? m.base_bits : m.delta_bits[c];
}

inline void pack(const Fields& f, uint8_t* out) {
    const Mode& m = MODES[f.mode];
    BitWriter128 w;
    w.put(m.code, m.code_bits);
    for (int k = 0; k < LAYOUT_BITS[f.mode]; ++k) {
        const uint8_t t = LAYOUT[f.mode][k];
        w.put((f.ep[t >> 6][(t >> 4) & 3] >> (t & 15)) & 1u, 1);
    }
    if (m.two_regions) {
        w.put(f.part & 31u, 5);
        const uint8_t a2 = anchor2(f.part);
        for (int p = 0; p < 16; ++p) w.put(f.idx[p], (p == 0 || p == a2) ? 2 : 3);
    } else {
        for (int p = 0; p < 16; ++p) w.put(f.idx[p], p == 0 ? 3 : 4);
    }
    w.write_to(out);
}

struct State {
    uint16_t ep[4][3];
    uint8_t ix[16];
};

// Optional dictionary (255 slots; slot = reference - block - 1 for a reference past the stream
// start). A null pointer or a false *_known entry means unknown. None ships in the tree.
struct Dictionary {
    const uint16_t (*ep)[4][3] = nullptr;
    const bool* ep_known = nullptr;
    const uint8_t (*ix)[16] = nullptr;
    const bool* ix_known = nullptr;
};

struct Stats {
    size_t blocks = 0;
    size_t exact = 0;           // both chains known
    size_t endpoints_only = 0;  // endpoints known, flat indices
    size_t copied = 0;          // endpoints from the nearest known block, flat indices
    size_t constant = 0;        // stream without any known endpoints
};

inline uint32_t il8(uint16_t e, uint16_t o) {
    uint32_t v = 0;
    for (int k = 0; k < 8; ++k) v |= ((e >> k) & 1u) << (2 * k) | ((o >> k) & 1u) << (2 * k + 1);
    return v;
}

inline uint32_t rev_hi(uint32_t v, uint32_t bits) {
    if (bits <= 11) return v;
    const uint32_t k = bits - 10, hi = (v >> 10) & ((1u << k) - 1);
    uint32_t r = 0;
    for (uint32_t j = 0; j < k; ++j) r |= ((hi >> j) & 1u) << (k - 1 - j);
    return (v & 1023u) | (r << 10);
}

inline uint32_t wrap(int32_t v, uint32_t bits) { return static_cast<uint32_t>(v) & ((1u << bits) - 1); }

// UF16 half 0x2000 (2^-7) as a mode-13 base; the same bits read as SF16 give 2.0.
inline constexpr uint16_t DEFAULT_FILL_BASE = 16913;

// fill_base: mode-13 base value for streams without known endpoints (0 = zero block).
// Returns false only on a malformed symbol stream (a mode code outside 0..13).
inline bool decode_blocks(const std::vector<uint16_t>& symbols, size_t nb, uint8_t* out, size_t cap,
                          Stats* stats, const Dictionary* dict = nullptr, uint16_t fill_base = DEFAULT_FILL_BASE) {
    if (cap < nb * 16) return false;
    const size_t t = nb * 2;
    auto sym = [&](int lane, size_t i, int h) -> uint16_t { return symbols[lane * t + 2 * i + h]; };
    std::vector<State> st(nb);
    std::vector<Fields> fl(nb);
    std::vector<uint8_t> kep(nb), kix(nb);
    static constexpr State HALF = { { { 0x8000, 0x8000, 0x8000 }, { 0x8000, 0x8000, 0x8000 },
                                      { 0x8000, 0x8000, 0x8000 }, { 0x8000, 0x8000, 0x8000 } },
                                    { 8, 8, 8, 8, 8, 8, 8, 8, 8, 8, 8, 8, 8, 8, 8, 8 } };
    for (size_t i = 0; i < nb; ++i) {
        const size_t x = interleave(sym(1, i, 0), sym(1, i, 1));
        const size_t er = static_cast<size_t>((static_cast<int32_t>(x) + unzigzag(interleave(sym(0, i, 0), sym(0, i, 1)))) & 0xFF);
        const size_t xr = x;
        const uint16_t (*pe)[3] = HALF.ep;
        const uint8_t* pq = HALF.ix;
        bool ke = true, kx = true;
        if (er != 0 && er <= i) { pe = st[i - er].ep; ke = kep[i - er]; }
        else if (er > i) {
            const size_t s = er - i - 1;
            if (dict && dict->ep && dict->ep_known && dict->ep_known[s]) pe = dict->ep[s];
            else ke = false;
        }
        if (xr != 0 && xr <= i) { pq = st[i - xr].ix; kx = kix[i - xr]; }
        else if (xr > i) {
            const size_t s = xr - i - 1;
            if (dict && dict->ix && dict->ix_known && dict->ix_known[s]) pq = dict->ix[s];
            else kx = false;
        }
        const uint16_t mode = sym(15, i, 0);
        if (mode >= 14) return false;
        const Mode& m = MODES[mode];
        Fields& f = fl[i];
        State& s = st[i];
        std::memcpy(s.ep, pe, sizeof s.ep);
        f.mode = static_cast<uint8_t>(mode);
        f.part = m.two_regions ? static_cast<uint8_t>(sym(15, i, 1) & 31) : 0;
        const int ne = m.two_regions ? 4 : 2;
        for (int e = 0; e < ne; ++e) {
            for (int c = 0; c < 3; ++c) {
                const uint32_t w = field_bits(m, e, c);
                const uint32_t raw = e < 2 ? il8(sym(2 + 3 * e + c, i, 0), sym(2 + 3 * e + c, i, 1))
                                           : sym(8 + c, i, e - 2);
                const uint32_t v = wrap(static_cast<int32_t>(pe[e][c] >> (16 - w)) + unzigzag(static_cast<uint16_t>(raw)), w);
                s.ep[e][c] = static_cast<uint16_t>(v << (16 - w));
                f.ep[e][c] = static_cast<uint16_t>(e == 0 ? rev_hi(v, m.base_bits) : v);
            }
        }
        if (!m.two_regions) {
            for (int c = 0; c < 3; ++c) {
                s.ep[2][c] = m.transformed
                    ? static_cast<uint16_t>(((static_cast<uint32_t>(s.ep[0][c] >> (16 - m.base_bits)) << (16 - m.delta_bits[c])) & 0xFFFF) ^ 0x8000)
                    : s.ep[0][c];
                s.ep[3][c] = s.ep[1][c];
            }
        }
        const uint32_t ib = m.two_regions ? 3 : 4;
        for (int k = 0; k < 4; ++k) {
            for (int h = 0; h < 2; ++h) {
                const uint16_t sv = sym(11 + k, i, h);
                uint32_t ev = 0, od = 0;
                for (uint32_t j = 0; j < ib; ++j) {
                    ev |= ((sv >> (2 * j)) & 1u) << j;
                    od |= ((sv >> (2 * j + 1)) & 1u) << j;
                }
                const uint32_t left = k < 3 ? od : ev, right = k < 3 ? ev : od;
                const int p0 = 4 * k + 2 * h;
                const uint32_t d[2] = { left, right };
                for (int q = 0; q < 2; ++q) {
                    const uint32_t v = wrap(static_cast<int32_t>(pq[p0 + q] >> (4 - ib)) + unzigzag(static_cast<uint16_t>(d[q])), ib);
                    s.ix[p0 + q] = static_cast<uint8_t>(v << (4 - ib));
                    f.idx[p0 + q] = static_cast<uint8_t>(v);
                }
            }
        }
        kep[i] = ke;
        kix[i] = kx;
    }

    Stats local;
    local.blocks = nb;
    auto flat = [](Fields& f) {
        const uint8_t v = MODES[f.mode].two_regions ? 3 : 7;  // anchors stay legal
        std::memset(f.idx, v, sizeof f.idx);
    };
    // nearest endpoint-known block in stream order (a tie takes the earlier one)
    std::vector<int64_t> nearest(nb, -1);
    int64_t last = -1;
    for (size_t i = 0; i < nb; ++i) { if (kep[i]) last = static_cast<int64_t>(i); nearest[i] = last; }
    last = -1;
    for (size_t i = nb; i-- > 0;) {
        if (kep[i]) last = static_cast<int64_t>(i);
        const int64_t at = static_cast<int64_t>(i);
        if (last >= 0 && (nearest[i] < 0 || last - at < at - nearest[i])) nearest[i] = last;
    }
    for (size_t i = 0; i < nb; ++i) {
        Fields f = fl[i];
        if (kep[i] && kix[i]) {
            ++local.exact;
        } else if (kep[i]) {
            flat(f);
            ++local.endpoints_only;
        } else if (nearest[i] >= 0) {
            f = fl[static_cast<size_t>(nearest[i])];
            flat(f);
            ++local.copied;
        } else {
            f = Fields{};
            f.mode = 13;
            for (int c = 0; c < 3; ++c) f.ep[0][c] = fill_base;  // x = 0: both endpoints equal
            ++local.constant;
        }
        pack(f, out + i * 16);
    }
    if (stats) *stats = local;
    return true;
}

// The whole BCPack BC6H stream: lanes, then rebuild. False when the lanes do not decode.
inline bool decode_stream(const unsigned char* input, size_t input_size, unsigned char* output, size_t output_size,
                          size_t* produced, Stats* stats, const Dictionary* dict = nullptr,
                          uint16_t fill_base = DEFAULT_FILL_BASE) {
    if (!input || !output || !produced || input_size == 0 || output_size == 0 || output_size % 16) return false;
    const size_t nb = output_size / 16;
    static constexpr uint8_t ab[16] = { 3, 3, 7, 7, 7, 4, 4, 4, 5, 5, 5, 7, 7, 7, 7, 4 };
    std::vector<uint16_t> symbols;
    if (!decode_lanes(input, input_size, ab, 16, nb * 2, symbols)) return false;
    if (!decode_blocks(symbols, nb, output, output_size, stats, dict, fill_base)) return false;
    *produced = output_size;
    return true;
}

