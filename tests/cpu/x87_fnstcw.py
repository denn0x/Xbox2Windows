"""Compare native and translated FNSTCW, FSTCW and WAIT of the x87 leaf-function profile, whose control
word is fixed at 0x027F.

Usage:
    python tests/cpu/x87_fnstcw.py asm <asm> <def>             regenerate the MASM source and exports
    python tests/cpu/x87_fnstcw.py emit <dll> <cpp> [control]   translate (and optionally mutate) the fixture
    python tests/cpu/x87_fnstcw.py check <harness> <native> <lifted> [controls...]

The exports, harness and guards follow tests/cpu/x87_add.py, and the loads, stores and FDIVP use the
format of tests/cpu/x87_div.py. emit checks that every decoded x87 instruction is the form its sequence
names; FSTCW decodes as WAIT followed by FNSTCW. The model stores 0x027F for each control-word store and
divides with the Fraction model of tests/cpu/x87_div.py, independent of tools/x87_soft.h.
"""
from pathlib import Path
import platform
import random
import re
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "tools"))
import x87_add as base  # noqa: E402  (tests/cpu is the script directory)
import x87_div as div  # noqa: E402
from x87_add import from_binary, m80_bytes, to_binary  # noqa: E402

INPUT, OUTPUT, SIZE = base.INPUT, base.OUTPUT, div.SIZE
CONTROL_WORD = 0x027F
WORD_OPS = ("fnstcw", "fstcw")

# ("fnstcw", offset), ("fstcw", offset) and ("wait",) are the new steps, and the others use the
# x87_div format. Control-word stores write the output block at RDX.
P80 = [("fld", "m80", 0), ("fld", "m80", 16)]
SEQUENCES = {
    "fnstcw_only": ("none", [("fnstcw", 0)]),
    "fstcw_only": ("none", [("fstcw", 6)]),
    # The stores between loads, a division and the final store leave the values unchanged.
    "fnstcw_values": ("pair80", [("fld", "m80", 0), ("fnstcw", 16), ("fld", "m80", 16), ("fstcw", 18),
                                 ("fdivp", "pop", 1), ("fnstcw", 20), ("fstp", "m80", 0)]),
    "wait_values": ("pair80", [("wait",), *P80, ("wait",), ("fdivp", "pop", 1), ("wait",), ("fstp", "m80", 0),
                               ("wait",)]),
    # Both stores at the edges of the output block, next to the guards.
    "fnstcw_edges": ("none", [("fnstcw", 0), ("fstcw", OUTPUT - 2)]),
    # A full stack: seven values back out as m64 and the eighth as m32 beside the word.
    "fstcw_depth8": ("m64x8", [("fld", "m64", 8 * k) for k in range(8)] + [("fstcw", 0), ("fstp", "m32", 4)]
                     + [("fstp", "m64", 8 * k) for k in range(7, 0, -1)]),
}

CONTROLS = {
    # The store gives 0x037F, the word FNINIT loads (64-bit precision).
    "fninit": (re.compile(r"store<uint16_t>\(a, 0x027f\); \}  // fnstcw"), "store<uint16_t>(a, 0x037f); }  // fnstcw"),
    # The store writes four bytes.
    "wide": (re.compile(r"store<uint16_t>\(a, 0x027f\); \}  // fnstcw"), "store<uint32_t>(a, 0x027f); }  // fnstcw"),
    # The store is dropped.
    "skip": (re.compile(r"store<uint16_t>\(a, 0x027f\); \}  // fnstcw"), "}  // fnstcw"),
    # The store keeps only the low byte of the word.
    "lowbyte": (re.compile(r"store<uint16_t>\(a, 0x027f\); \}  // fnstcw"), "store<uint8_t>(a, 0x7f); }  // fnstcw"),
}


# ---- MASM generation and decoding ------------------------------------------------------------------

def asm_line(step):
    if step[0] in WORD_OPS:
        return f"    {step[0]} word ptr [rdx+{step[1]}]"
    if step[0] == "wait":
        return "    wait"
    return div.asm_line(step)


def expected_forms(step):
    """The decoded x87 instructions of a step: FSTCW is WAIT then FNSTCW."""
    if step[0] == "fnstcw":
        return [("fnstcw", "m16")]
    if step[0] == "fstcw":
        return [("wait", ""), ("fnstcw", "m16")]
    if step[0] == "wait":
        return [("wait", "")]
    return [div.expected_form(step)]


def decoded_form(i):
    from iced_x86 import Mnemonic as M

    if i.mnemonic == M.WAIT:
        return "wait", ""
    if i.mnemonic == M.FNSTCW:
        return "fnstcw", "m16"
    return div.decoded_form(i)


def write_asm(asm_path, def_path):
    lines = ["; coverage: source cpu_aot_x87_fnstcw",
             "; Generated by tests/cpu/x87_fnstcw.py asm; edit SEQUENCES there and regenerate.",
             "; Source-owned differential fixture for FNSTCW, FSTCW and WAIT in the x87 leaf-function profile.",
             "; Each export reads an input block at RCX, writes an output block at RDX and returns with the x87",
             "; stack empty.", ".code", ""]
    for name, (_, steps) in SEQUENCES.items():
        lines += [f"{name} PROC FRAME", "    .endprolog", *(asm_line(s) for s in steps), "    ret", f"{name} ENDP", ""]
    lines.append("END")
    Path(asm_path).write_text("\n".join(lines) + "\n", encoding="ascii")
    Path(def_path).write_text("EXPORTS\n" + "".join(f"    {name}\n" for name in SEQUENCES), encoding="ascii")


def emit(image, output, control="lifted"):
    import pefile
    from cpu_leaf_aot import export_rva
    from cpu_ranges import function_ranges
    from ffx_version_query import INTEGER_HEADER, lower, region
    from x87_lower import X87_HEADER, is_x87

    parts = [INTEGER_HEADER, X87_HEADER]
    with pefile.PE(str(image), fast_load=True) as pe:
        for name, (_, steps) in SEQUENCES.items():
            (bounds,) = function_ranges(pe, export_rva(pe, name))
            body = region(pe, *bounds)
            decoded = [decoded_form(i) for i in body if is_x87(i)]
            wanted = [form for s in steps for form in expected_forms(s)]
            if decoded != wanted:
                raise AssertionError(f"{name} assembled as {decoded}, expected {wanted}")
            code = lower(body, ["rcx = a; rdx = b;"], {}, {}, {}, x87=True)
            parts.append(f'extern "C" __declspec(dllexport) word {name}(word a, word b) {{\n{code}\n}}\n')
    text = "".join(parts)
    if control != "lifted":
        expression, replacement = CONTROLS[control]
        text, count = expression.subn(replacement, text)
        if not count:
            raise AssertionError(f"control {control} changed nothing")
        print(f"control {control}: {count} replacements")
    output.write_text(text, encoding="ascii")


# ---- Independent model -----------------------------------------------------------------------------

def reference(name, data):
    slots, out = [], bytearray(b"\xcc" * OUTPUT)

    def read(kind, offset):
        return int.from_bytes(data[offset:offset + SIZE[kind]], "little")

    for op, *args in SEQUENCES[name][1]:
        if op in WORD_OPS:
            out[args[0]:args[0] + 2] = CONTROL_WORD.to_bytes(2, "little")
        elif op == "wait":
            pass
        elif op == "fld":
            raw = read(*args)
            slots.append((raw & (2 ** 64 - 1), raw >> 64) if args[0] == "m80" else from_binary(args[0], raw))
        elif op == "fstp":
            kind, offset = args
            v = slots.pop()
            encoded = v[0] | v[1] << 64 if kind == "m80" else to_binary(kind, v)
            out[offset:offset + SIZE[kind]] = encoded.to_bytes(SIZE[kind], "little")
        else:  # ("fdivp", "pop", 1)
            slots[-2] = div.div(slots[-2], slots[-1])
            slots.pop()
    assert not slots
    return bytes(out)


# ---- Inputs ----------------------------------------------------------------------------------------

def cases():
    rng = random.Random(107)
    singles = list(base.m80_singles())
    f64 = base.f64_bits()
    blocks = {
        "none": [bytes(rng.getrandbits(8) for _ in range(INPUT)) for _ in range(20)],
        "pair80": [m80_bytes(a) + m80_bytes(b) for a in base.special_m80() for b in base.special_m80()[::3]]
                  + [m80_bytes(rng.choice(singles)) + m80_bytes(rng.choice(singles)) for _ in range(300)],
        "m64x8": [b"".join(rng.choice(f64).to_bytes(8, "little") for _ in range(8)) for _ in range(300)],
    }
    for name, (kind, _) in SEQUENCES.items():
        for block in blocks[kind]:
            yield name, bytes(block).ljust(INPUT, b"\0")


# ---- Check -----------------------------------------------------------------------------------------

def check(harness_path, native_path, lifted_path, *control_paths):
    expected = [(name, data, reference(name, data)) for name, data in cases()]
    for label, path in (("native", native_path), ("lifted", lifted_path)):
        run = base.Runner(harness_path, path)
        bad = 0
        for name, data, want in expected:
            got, state = run(name, data)
            if not base.entry_state_ok(state):
                raise AssertionError(f"{label} {name} left state {state:#014x}; the profile requires control "
                                     "0x027f and an empty stack at TOP 0")
            if got != want:
                if bad < 3:
                    print(f"{label} mismatch: {name}(input {data[:32].hex()})\n  got      {got.hex()}\n"
                          f"  expected {want.hex()}")
                bad += 1
        if bad:
            raise AssertionError(f"{label}: {bad}/{len(expected)} mismatches")
    stores = sum(1 for _, (_, steps) in SEQUENCES.items() for s in steps if s[0] in WORD_OPS)
    print(f"{len(expected)} cases over {len(SEQUENCES)} exports (output block and guards) matched the reference "
          "in native and translated DLLs; each export returned with control 0x027f and an empty stack")
    print(f"each of the {stores} control-word stores wrote {CONTROL_WORD:#06x} in the native and translated DLLs")
    print(f"processor: {platform.processor()}")
    first = {}
    for name, data, want in expected:
        first.setdefault(name, (data, want))
    for label, path in (("native", native_path), ("lifted", lifted_path)):
        run = base.Runner(harness_path, path)
        failed = [name for name, (data, want) in first.items() if not base.preserved(run, "x87_call", name, data, want)]
        if failed:
            raise AssertionError(f"x87_call lost a live caller value or control word around {label} {failed}")
    print(f"x87_call kept a live caller ST(0) value and control word around all {len(first)} native and "
          "translated exports")
    for path in control_paths:
        control = Path(path).stem.rsplit("_", 1)[-1]
        run = base.Runner(harness_path, path)
        bad = 0
        for name, data, want in expected:
            try:
                bad += run(name, data)[0] != want
            except AssertionError:  # a store outside the output block
                bad += 1
        print(f"control {control}: {bad}/{len(expected)} mismatches")
        if not bad:
            raise AssertionError(f"control {control} matched every case")
    check_rejections()


def check_rejections():
    from iced_x86 import Decoder
    from ffx_version_query import lower

    def attempt(hex_bytes):
        body = list(Decoder(64, bytes.fromhex(hex_bytes), ip=0x1000))
        try:
            lower(body, [], {}, {}, {}, x87=True)
        except ValueError as exc:
            return str(exc)
        return None

    fld, fstp = "db 29", "db 3a"  # fld tbyte ptr [rcx]; fstp tbyte ptr [rdx]
    rejected = {
        "fldcw m16": (attempt(f"d9 29 {fld} {fstp} c3"), "unsupported x87 operation"),
        "fstcw then fldcw": (attempt(f"9b d9 3a d9 2a {fld} {fstp} c3"), "unsupported x87 operation"),
        "fninit": (attempt(f"{fld} db e3 {fstp} c3"), "unsupported x87 operation"),
        "fnstsw m16": (attempt(f"{fld} dd 3a {fstp} c3"), "stores status-word bits"),
        "fdecstp": (attempt(f"d9 f6 {fld} {fstp} c3"), "unsupported x87 operation"),
    }
    for case, (message, needle) in rejected.items():
        if message is None or needle not in message:
            raise AssertionError(f"{case}: expected a rejection containing {needle!r}, got {message!r}")
    print(f"rejected {len(rejected)} sequences outside the profile: " + "; ".join(rejected))


if __name__ == "__main__":
    mode, first, second, *rest = sys.argv[1:]
    if mode == "asm":
        write_asm(first, second)
    elif mode == "emit":
        emit(Path(first), Path(second), *rest)
    elif mode == "check":
        check(first, second, *rest)
    else:
        raise ValueError(mode)
